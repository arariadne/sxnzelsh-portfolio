// Renders the Open Graph card (1200x630) and the favicon set with the site's own
// fonts and portrait, using the installed Edge/Chrome through Playwright.
// Run after `npm run images`:  node scripts/brand-assets.mjs
import { chromium } from 'playwright';
import sharp from 'sharp';
import { readFile, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const pub = path.join(root, 'public');
const font = (pkg, file) => path.join(root, 'node_modules', pkg, 'files', file);
const assets = {
  '/fonts/bricolage.woff2': [font('@fontsource-variable/bricolage-grotesque', 'bricolage-grotesque-latin-opsz-normal.woff2'), 'font/woff2'],
  '/fonts/hanken.woff2': [font('@fontsource-variable/hanken-grotesk', 'hanken-grotesk-latin-wght-normal.woff2'), 'font/woff2'],
  '/fonts/serif.woff2': [font('@fontsource/instrument-serif', 'instrument-serif-latin-400-italic.woff2'), 'font/woff2'],
  '/portrait.jpg': [path.join(pub, 'img', 'portrait-640.jpg'), 'image/jpeg'], // generated by npm run images,
};

