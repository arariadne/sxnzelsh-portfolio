const icon = `<!doctype html><html><head>${base}<style>
.i{width:512px;height:512px;background:#230F3B;display:flex;align-items:center;justify-content:center;font-family:B;font-weight:800;letter-spacing:-.04em;font-size:400px;line-height:1;padding-bottom:56px}
.i span{color:#FF9CCB}
</style></head><body><div class="i">e<span>.</span></div></body></html>`;

const browser = await chromium.launch({ channel: existsSync('C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe') ? 'msedge' : 'chrome' });

async function render(html, width, height) {
  const page = await (await browser.newContext({ viewport: { width, height }, deviceScaleFactor: 1 })).newPage();
  await page.route('http://brand.local/**', async (r) => {
    const { pathname } = new URL(r.request().url());
    if (pathname === '/') return r.fulfill({ contentType: 'text/html', body: html });
    const [file, type] = assets[pathname] ?? [];
    if (!file) return r.fulfill({ status: 404, body: '' });
    r.fulfill({ contentType: type, body: await readFile(file) });
  });
  await page.goto('http://brand.local/', { waitUntil: 'networkidle' });
  await page.evaluate(() => document.fonts.ready);
  const png = await page.screenshot({ clip: { x: 0, y: 0, width, height } });
  await page.context().close();
  return png;
}

// Open Graph / Twitter card
const ogPng = await render(og, 1200, 630);
await sharp(ogPng).png({ compressionLevel: 9, palette: false }).toFile(path.join(pub, 'og-card.png'));

// Favicons
const iconPng = await render(icon, 512, 512);
await sharp(iconPng).png().toFile(path.join(pub, 'icon-512.png'));
await sharp(iconPng).resize(192).png().toFile(path.join(pub, 'icon-192.png'));
await sharp(iconPng).resize(180).png().toFile(path.join(pub, 'apple-touch-icon.png'));

// favicon.ico with 16, 32 and 48px PNG entries.
const sizes = [16, 32, 48];
const pngs = await Promise.all(sizes.map((s) => sharp(iconPng).resize(s).png().toBuffer()));
const header = Buffer.alloc(6 + 16 * sizes.length);
header.writeUInt16LE(0, 0);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(sizes.length, 4);
let offset = header.length;
sizes.forEach((s, i) => {
  const e = 6 + i * 16;
  header.writeUInt8(s, e);
  header.writeUInt8(s, e + 1);
  header.writeUInt8(0, e + 2);
  header.writeUInt8(0, e + 3);
  header.writeUInt16LE(1, e + 4);
  header.writeUInt16LE(32, e + 6);
  header.writeUInt32LE(pngs[i].length, e + 8);
  header.writeUInt32LE(offset, e + 12);
  offset += pngs[i].length;
});
await writeFile(path.join(pub, 'favicon.ico'), Buffer.concat([header, ...pngs]));

await browser.close();
console.log('wrote og-card.png, icon-512.png, icon-192.png, apple-touch-icon.png, favicon.ico');
